/**
 * The database generates a primary key only when `@pk` says `generated: true`
 * (or by the type default: numbers, `"serial"`, `"uuid"`). Otherwise decaf
 * fills it — another decorator (`@uuid()`, `@composed()`, …) or the caller —
 * before the record reaches TypeORM. Both must hold for models defined after
 * the TypeORM decoration and for models re-flavoured with `uses()` (the core
 * TaskEngine models).
 */
// Must load first: these models are defined before for-typeorm decorates.
import { EarlyManualModel, EarlyUuidModel } from "./models/EarlyDefinedModels";
import { TypeORMAdapter, TypeORMFlavour } from "../../src";
import { column, pk, Repository, table, uuid } from "@decaf-ts/core";
import { uses } from "@decaf-ts/decoration";
import { Model, model, required, type ModelArg } from "@decaf-ts/decorator-validation";
import { ConflictError, NotFoundError } from "@decaf-ts/db-decorators";
import type { DataSource, DataSourceOptions } from "typeorm";

uses(TypeORMFlavour)(EarlyUuidModel);
uses(TypeORMFlavour)(EarlyManualModel);

jest.setTimeout(60000);

@table("pkgen_late_uuid")
@uses(TypeORMFlavour)
@model()
class LateUuidModel extends Model {
  @pk()
  @uuid()
  id!: string;

  @column()
  @required()
  name!: string;

  constructor(arg?: ModelArg<LateUuidModel>) {
    super(arg);
  }
}

/** `generated: false` overrides the uuid type's database default. */
@table("pkgen_late_uuid_manual")
@uses(TypeORMFlavour)
@model()
class LateUuidManualModel extends Model {
  @pk({ type: "uuid", generated: false })
  @uuid()
  id!: string;

  @column()
  @required()
  name!: string;

  constructor(arg?: ModelArg<LateUuidManualModel>) {
    super(arg);
  }
}

/** The database generates it. */
@table("pkgen_late_db_uuid")
@uses(TypeORMFlavour)
@model()
class LateDbUuidModel extends Model {
  @pk({ type: "uuid" })
  id!: string;

  @column()
  @required()
  name!: string;

  constructor(arg?: ModelArg<LateDbUuidModel>) {
    super(arg);
  }
}

const admin: DataSourceOptions = {
  type: "postgres",
  username: process.env.TYPEORM_ADMIN_USER || "alfred",
  password: process.env.TYPEORM_ADMIN_PASSWORD || "password",
  database: process.env.TYPEORM_ADMIN_DATABASE || "alfred",
  host: process.env.TYPEORM_HOST || "localhost",
  port: Number(process.env.TYPEORM_PORT || "5432"),
};
const dbName = `pk_generation_${Date.now().toString(36)}`;
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;


describe("primary keys generated by decaf vs the database", () => {
  let adapter: TypeORMAdapter;

  /** Whether TypeORM leaves the key to the database. */
  function isDbGenerated(model: new (...args: never[]) => unknown): boolean {
    const meta = (adapter.client as DataSource)
      .entityMetadatas.find((m) => m.tableName === Model.tableName(model as never));
    if (!meta) throw new Error(`no entity for ${model.name}`);
    return meta.primaryColumns[0].isGenerated;
  }

  beforeAll(async () => {
    const con = await TypeORMAdapter.connect(admin);
    try {
      await TypeORMAdapter.createDatabase(con, dbName);
    } catch (e: unknown) {
      if (!(e instanceof ConflictError)) throw e;
    } finally {
      await con.destroy();
    }
    adapter = new TypeORMAdapter({
      ...admin,
      database: dbName,
      synchronize: true,
      logging: false,
    } as DataSourceOptions);
    await adapter.initialize();
  });

  afterAll(async () => {
    await adapter?.shutdown();
    const con = await TypeORMAdapter.connect(admin);
    try {
      await TypeORMAdapter.deleteDatabase(con, dbName);
    } catch (e: unknown) {
      if (!(e instanceof NotFoundError)) throw e;
    } finally {
      await con.destroy();
    }
  });

  it("decaf fills @pk() + @uuid() (model defined after the TypeORM decoration)", async () => {
    expect(isDbGenerated(LateUuidModel)).toBe(false);
    const created = await Repository.forModel(LateUuidModel, adapter.alias).create(
      new LateUuidModel({ name: "late" })
    );
    expect(created.id).toMatch(UUID);
  });

  it("decaf fills @pk() + @uuid() (model re-flavoured with uses(), like TaskModel)", async () => {
    expect(isDbGenerated(EarlyUuidModel)).toBe(false);
    const repo = Repository.forModel(EarlyUuidModel, adapter.alias);
    const created = await repo.create(new EarlyUuidModel({ name: "early" }));
    expect(created.id).toMatch(UUID);
    expect((await repo.read(created.id)).name).toBe("early");
  });

  it("keeps a caller-supplied key (model re-flavoured with uses())", async () => {
    const repo = Repository.forModel(EarlyManualModel, adapter.alias);
    const created = await repo.create(new EarlyManualModel({ id: "manual-1", name: "m" }));
    expect(created.id).toBe("manual-1");
  });

  it("`generated: false` on a uuid key leaves generation to decaf", async () => {
    expect(isDbGenerated(LateUuidManualModel)).toBe(false);
    const created = await Repository.forModel(LateUuidManualModel, adapter.alias).create(
      new LateUuidManualModel({ name: "u" })
    );
    expect(created.id).toMatch(UUID);
  });

  it("the database generates `@pk({ type: \"uuid\" })`", async () => {
    expect(isDbGenerated(LateDbUuidModel)).toBe(true);
    const created = await Repository.forModel(LateDbUuidModel, adapter.alias).create(
      new LateDbUuidModel({ name: "db" })
    );
    expect(created.id).toMatch(UUID);
  });

});
